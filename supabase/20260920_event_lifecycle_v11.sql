-- FTS Selfie Event lifecycle + scan statistics v11
-- Apply this migration in Supabase SQL editor before merging the matching frontend branch.

create table if not exists public.fts_event_lifecycle_v11 (
  event_token text primary key,
  schedule jsonb not null default '[]'::jsonb,
  gallery_url text not null default '',
  gallery_available_at text not null default '',
  link_expires_at text not null default '',
  test_days_before integer not null default 0,
  updated_at timestamptz not null default now()
);

create table if not exists public.fts_event_scans_v11 (
  id bigint generated by default as identity primary key,
  event_token text not null,
  scanned_at timestamptz not null default now()
);

create index if not exists fts_event_scans_v11_event_token_idx
  on public.fts_event_scans_v11(event_token);
create index if not exists fts_event_scans_v11_scanned_at_idx
  on public.fts_event_scans_v11(scanned_at);

alter table public.fts_event_lifecycle_v11 enable row level security;
alter table public.fts_event_scans_v11 enable row level security;

revoke all on public.fts_event_lifecycle_v11 from anon, authenticated;
revoke all on public.fts_event_scans_v11 from anon, authenticated;

create or replace function public.fts_admin_set_event_lifecycle_v11(
  p_admin_code text,
  p_event_token text,
  p_schedule jsonb,
  p_gallery_url text default '',
  p_gallery_available_at text default '',
  p_link_expires_at text default '',
  p_test_days_before integer default 0
)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  if not exists (
    select 1
    from public.fts_admin_dashboard_events(p_admin_code) d
    where d.event_token::text = p_event_token::text
  ) then
    raise exception 'Not authorized for this event';
  end if;

  insert into public.fts_event_lifecycle_v11(
    event_token,schedule,gallery_url,gallery_available_at,link_expires_at,test_days_before,updated_at
  )
  values(
    p_event_token::text,
    coalesce(p_schedule,'[]'::jsonb),
    coalesce(p_gallery_url,''),
    coalesce(p_gallery_available_at,''),
    coalesce(p_link_expires_at,''),
    greatest(0,coalesce(p_test_days_before,0)),
    now()
  )
  on conflict(event_token) do update set
    schedule=excluded.schedule,
    gallery_url=excluded.gallery_url,
    gallery_available_at=excluded.gallery_available_at,
    link_expires_at=excluded.link_expires_at,
    test_days_before=excluded.test_days_before,
    updated_at=now();
end;
$$;

